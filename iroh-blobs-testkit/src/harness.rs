//! Running one case: store lifecycle, timeouts and property test setup.
use std::time::Duration;

use anyhow::{anyhow, bail, Context};
use iroh_blobs::api::Store;
use proptest::{
    strategy::Strategy,
    test_runner::{Config as ProptestConfig, TestCaseError, TestRunner},
};

use crate::testkit::{Factory, TestStore};

/// Settings for running cases.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Settings {
    /// Number of generated inputs per property.
    pub proptest_cases: u32,
    /// Time limit for one run, including store creation and shutdown.
    pub timeout: Duration,
}

/// Runs the checks of one case, each run against a fresh store.
pub(crate) struct Harness {
    runtime: tokio::runtime::Runtime,
    factory: Factory,
    settings: Settings,
}

impl Harness {
    pub fn new(factory: Factory, settings: Settings) -> Self {
        let runtime = tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()
            .expect("failed to create tokio runtime");
        Self {
            runtime,
            factory,
            settings,
        }
    }

    /// Runs `test` against a fresh store for every input generated by
    /// `strategy`. On failure, the error contains the minimal failing input.
    pub fn check_prop<S>(
        &self,
        strategy: S,
        test: impl AsyncFn(Store, S::Value) -> anyhow::Result<()>,
    ) -> anyhow::Result<()>
    where
        S: Strategy,
    {
        let config = ProptestConfig {
            cases: self.settings.proptest_cases,
            // Failures would be persisted relative to this crate's sources,
            // which are read only when used as a dependency.
            failure_persistence: None,
            ..ProptestConfig::default()
        };
        let mut runner = TestRunner::new(config);
        runner
            .run(&strategy, |input| {
                self.runtime
                    .block_on(self.with_store(async |store| test(store, input).await))
                    .map_err(|cause| TestCaseError::fail(format!("{cause:#}")))
            })
            .map_err(|cause| anyhow!("{cause}"))
    }

    /// Creates a store, runs `test` against it and shuts it down.
    async fn with_store(
        &self,
        test: impl AsyncFnOnce(Store) -> anyhow::Result<()>,
    ) -> anyhow::Result<()> {
        let timeout = self.settings.timeout;
        let TestStore { store, guard } = tokio::time::timeout(timeout, (self.factory)())
            .await
            .map_err(|_| anyhow!("store factory timed out after {timeout:?}"))?
            .context("store factory failed")?;
        let result = match tokio::time::timeout(timeout, test(store.clone())).await {
            Ok(result) => result,
            Err(_) => Err(anyhow!(
                "timed out after {timeout:?}: a store must answer every request and end every stream"
            )),
        };
        // Shut down even if the test failed, so the store releases its resources.
        let shutdown = tokio::time::timeout(timeout, store.shutdown()).await;
        drop(guard);
        result?;
        match shutdown {
            Ok(Ok(())) => Ok(()),
            Ok(Err(cause)) => bail!("shutdown failed: {cause}"),
            Err(_) => bail!("shutdown timed out after {timeout:?}"),
        }
    }
}
